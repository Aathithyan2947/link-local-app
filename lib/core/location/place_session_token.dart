import 'dart:math';

/// A random v4 UUID — the session-token format Google Places expects. One token spans a
/// run of autocomplete keystrokes plus the details call that ends it, so the whole search
/// is billed as a single session.
String newPlaceSessionToken() {
  final r = Random.secure();
  final b = List<int>.generate(16, (_) => r.nextInt(256));
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  final h = b.map((x) => x.toRadixString(16).padLeft(2, '0')).join();
  return '${h.substring(0, 8)}-${h.substring(8, 12)}-${h.substring(12, 16)}-${h.substring(16, 20)}-${h.substring(20)}';
}
